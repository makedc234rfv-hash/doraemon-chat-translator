    fun keyHintFor(provider: AiProvider): String = when (provider) {
        AiProvider.GEMINI -> hintKeyGemini
        AiProvider.DEEPSEEK -> hintKeyDeepSeek
        AiProvider.OPENAI -> hintKeyOpenAi
        AiProvider.CUSTOM -> hintKeyCustom
    }

    fun sizeLabel(size: OverlaySize): String = when (size) {
        OverlaySize.SMALL -> overlaySizeSmall
        OverlaySize.MEDIUM -> overlaySizeMedium
        OverlaySize.LARGE -> overlaySizeLarge
    }

    fun replyLangLabel(lang: ReplyLanguage): String = when (lang) {
        ReplyLanguage.AUTO -> replyLangAuto
        else -> lang.shortLabel
    }
}

